x=int(input("What's x ?"))
y=int(input("What's y ?"))

#using if condition
if x>y:
    print("x is greater than y ")
if x<y:
    print("x is less than y ")
if x==y:
    print("x equals to y ")

#using the elif condition
if x>y:
    print("x is greater than y ")
elif x<y:
    print("x is less than y ")
elif x==y:
    print("x equals to y ")
    
#using else condition 
if x>y:
    print("x is greater than y ")
if x<y:
    print("x is less than y ")
else:
    print("x equals to y ")